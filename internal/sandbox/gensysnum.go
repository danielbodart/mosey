//go:build ignore

// gensysnum writes sysnum.go: the syscall numbers of linux/amd64 and
// linux/arm64, read from the pinned golang.org/x/sys's own generated tables,
// so the seccomp compiler can build and test a filter for either
// architecture on any host (server.md §6.3). Run it with go generate after
// bumping x/sys; TestSyscallTableMatchesTheHost checks the result.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var line = regexp.MustCompile(`^\s*SYS_([A-Z0-9_]+)\s*=\s*([0-9]+)\s*$`)

func main() {
	dir, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "golang.org/x/sys").Output()
	if err != nil {
		fail(fmt.Errorf("finding golang.org/x/sys: %w", err))
	}
	version, err := exec.Command("go", "list", "-m", "-f", "{{.Version}}", "golang.org/x/sys").Output()
	if err != nil {
		fail(err)
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by gensysnum.go from golang.org/x/sys %s; DO NOT EDIT.\n\npackage sandbox\n\n",
		strings.TrimSpace(string(version)))
	for _, arch := range []string{"amd64", "arm64"} {
		path := filepath.Join(strings.TrimSpace(string(dir)), "unix", "zsysnum_linux_"+arch+".go")
		nums, err := read(path)
		if err != nil {
			fail(err)
		}
		names := make([]string, 0, len(nums))
		for n := range nums {
			names = append(names, n)
		}
		sort.Strings(names)
		fmt.Fprintf(&out, "var sysnum%s = map[string]uint32{\n", strings.ToUpper(arch))
		for _, n := range names {
			fmt.Fprintf(&out, "\t%q: %d,\n", n, nums[n])
		}
		fmt.Fprintf(&out, "}\n\n")
	}
	src, err := format.Source(out.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile("sysnum.go", src, 0o644); err != nil {
		fail(err)
	}
}

func read(path string) (map[string]uint32, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	nums := map[string]uint32{}
	s := bufio.NewScanner(f)
	for s.Scan() {
		m := line.FindStringSubmatch(s.Text())
		if m == nil {
			continue
		}
		n, err := strconv.ParseUint(m[2], 10, 32)
		if err != nil {
			return nil, err
		}
		nums[strings.ToLower(m[1])] = uint32(n)
	}
	return nums, s.Err()
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gensysnum:", err)
	os.Exit(1)
}
