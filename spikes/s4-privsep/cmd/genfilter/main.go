// genfilter writes cmd/mosey-spike/prefilter_linux_<arch>.go: the
// PreRuntimePolicy compiled to BPF as a statically-initialised Go array, so
// the assembly entry stub (prestart_linux_<arch>.s) can install it before
// the Go runtime has run a single instruction.
package main

import (
	"fmt"
	"os"

	"mosey.spike/s4-privsep/sandbox"
)

func main() {
	for _, a := range []sandbox.Arch{sandbox.AMD64, sandbox.ARM64} {
		prog, missing, err := sandbox.Program(a, sandbox.PreRuntimePolicy(sandbox.KillProcess))
		if err != nil {
			panic(err)
		}
		path := fmt.Sprintf("cmd/mosey-spike/prefilter_linux_%s.go", a.Name)
		f, err := os.Create(path)
		if err != nil {
			panic(err)
		}
		fmt.Fprintf(f, "// Code generated by cmd/genfilter; DO NOT EDIT.\n// policy %q, %d instructions, skipped %v\n\n", "net-preruntime", len(prog), missing)
		fmt.Fprintf(f, "package main\n\nimport \"golang.org/x/sys/unix\"\n\n")
		fmt.Fprintf(f, "// preFilter and preFprog are laid out by the linker (no init code), so\n// they are valid at the ELF entry point.\nvar preFilter = [%d]unix.SockFilter{\n", len(prog))
		for _, in := range prog {
			fmt.Fprintf(f, "\t{Code: %#04x, Jt: %d, Jf: %d, K: %#08x},\n", in.Code, in.Jt, in.Jf, in.K)
		}
		fmt.Fprintf(f, "}\n\nvar preFprog = unix.SockFprog{Len: %d, Filter: &preFilter[0]}\n", len(prog))
		f.Close()
		fmt.Println("wrote", path)
	}
}
